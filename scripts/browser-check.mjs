import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
const base = process.env.TEST_BASE_URL || 'http://127.0.0.1:3006';
const browser = await chromium.launch();
const page = await browser.newPage();
const errors=[]; page.on('pageerror', e=>errors.push(e.message));
await page.goto(base);
await page.locator('summary').nth(1).click();
assert.equal(await page.locator('details').nth(1).getAttribute('open'), '');
await page.locator('#waitlist-form button').click();
assert.match(await page.locator('#form-status').innerText(), /valid email/);
await page.route('**/api/waitlist/', route=>route.fulfill({status:503,contentType:'application/json',body:'{"error":"unavailable"}'}));
await page.locator('#email').fill('test@example.com');
await page.locator('#waitlist-form button').click();
await page.getByText('Something went wrong. Please try again.').waitFor();
assert.equal(await page.locator('#email').inputValue(),'test@example.com');
await page.unroute('**/api/waitlist/');
await page.route('**/api/waitlist/', route=>route.fulfill({status:200,contentType:'application/json',body:'{"ok":true}'}));
await page.locator('#waitlist-form button').click();
await page.getByText('Thanks — you’re on the list.').waitFor();
assert.equal(await page.locator('#email').inputValue(),'');
await page.goto(base+'/docs/');
await page.getByRole('heading',{name:'Counter documentation',exact:true}).waitFor();
await page.screenshot({path:'/tmp/counter-docs-desktop.png',fullPage:true});
const search=await page.request.get(base+'/api/search?query=documentation');
assert.equal(search.status(),200);
assert.ok((await search.json()).length>0);
await page.evaluate(() => { window.__docsNavigationMarker = true; });
await page.locator('a[href="/platform/"]').first().click();
await page.waitForURL('**/platform/');
await page.waitForFunction(() => window.__docsNavigationMarker === undefined);
await page.goto(base + '/docs/', { waitUntil: 'networkidle' });
await page.setViewportSize({width:390,height:844});
await page.reload({ waitUntil: 'networkidle' });
await page.evaluate(() => document.fonts.ready);
await page.screenshot({path:'/tmp/counter-docs-mobile.png',fullPage:true});
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
assert.equal((await page.request.get(base+'/docs/missing/')).status(),404);
assert.equal((await page.request.get(base+'/blog/missing/')).status(),404);
for(const [body,status] of [[{email:'bad'},400],[{email:'test@example.com',role:'agency',website:'spam'},400]]) {
 assert.equal((await page.request.post(base+'/api/waitlist/',{data:body})).status(),status);
}
assert.equal((await page.request.post(base+'/api/waitlist/',{data:{email:'test@example.com',role:'agency'},headers:{Origin:'https://other.example'}})).status(),403);
assert.equal((await page.request.post(base+'/api/waitlist/',{data:'x'.repeat(5000),headers:{'Content-Type':'application/json'}})).status(),413);
assert.deepEqual(errors,[]);
await browser.close();
console.log('Browser checks passed: FAQ, form validation/error/success, docs, search, docs-to-marketing isolation, mobile overflow, 404s, API rejection cases.');
